def generate_servo_lock_cap(out_path):
    """
    Силова кришка-фіксатор серви (servo_lock_cap.stl) для ВЖЕ НАДРУКОВАНОГО корпусу switch_mount_frame.stl!
    Друкується дахом донизу на столі (Z_print = 0..37.8 мм) БЕЗ САПОРТІВ за ~15 хвилин!
    Як працює:
    1. Одягається зверху на серву та зовнішні стінки ложа серви (X = -85.7..-43.0, Y = -21.0..+42.0).
    2. Суцільний дах (товщина 3.5 мм) + центральна прижимна плита (Z = 34.8..37.5 мм) та 2 внутрішні колодки
       у пази монтажних вушок серви (Z = 29.0..37.5 мм) намертво притискають серву до дна подіуму (Z = 14.0 мм).
    3. Три глибокі зовнішні стінки охоплюють ложе серви ззовні на всю глибину (до Z = 3.2 мм) із внутрішніми
       зубцями натягу (Crush Ribs 0.5 мм), які вгризаються в шари 3D-друку і не дають серві виштовхнути кришку!
    """
    tris = []
    z_top = 41.0

    def add_cap_box(x0, y0, z0_frame, x1, y1, z1_frame):
        # Перевертаємо Z так, щоб плоский дах z_top = 41.0 лежав на столі принтера Z_print = 0.0 (без сапортів!)
        zp0 = z_top - z1_frame
        zp1 = z_top - z0_frame
        add_box(tris, x0, y0, zp0, x1, y1, zp1)

    # 1. Плоский силовий дах кришки (Z_frame = 37.5 .. 41.0 мм -> Z_print = 0.0 .. 3.5 мм)
    add_cap_box(-89.2, -24.5, 37.5, -43.0, 45.5, 41.0)

    # 2. Внутрішня прижимна плита прямо на сріблястий корпус серви (Z_frame = 34.8 .. 37.5 мм)
    add_cap_box(-82.0, -9.4, 34.8, -43.0, 30.4, 37.5)

    # 3. Дві внутрішні колодки-фіксатори в пази монтажних вушок серви (Z_frame = 29.0 .. 37.5 мм)
    #    Верхнє вушко (Y = 32.1 .. 38.6 мм) та нижнє вушко (Y = -17.6 .. -11.1 мм)
    add_cap_box(-58.1,  32.1, 29.0, -45.9,  38.6, 37.5)
    add_cap_box(-58.1, -17.6, 29.0, -45.9, -11.1, 37.5)

    # 4. Верхня зовнішня силова стінка (Y = 42.1 .. 45.5 мм, опускається до самої основи Z_frame = 3.2 мм)
    add_cap_box(-89.2, 42.1, 3.2, -43.0, 45.5, 37.5)
    # Пружні ребра натягу (Crush Ribs 0.5 мм) на верхній стінці (вгризаються в шари стінки Y = 42.0 мм)
    for rx in (-82.0, -68.0, -54.0):
        add_cap_box(rx, 41.6, 5.0, rx + 3.0, 42.1, 36.0)

    # 5. Ліва (задня) зовнішня силова стінка (X = -89.2 .. -85.8 мм, опускається до Z_frame = 3.2 мм)
    add_cap_box(-89.2, -24.5, 3.2, -85.8, 45.5, 37.5)
    for ry in (-12.0, 8.0, 28.0):
        add_cap_box(-85.8, ry, 5.0, -85.3, ry + 3.0, 36.0)

    # 6. Нижня зовнішня силова стінка (Y = -24.5 .. -21.1 мм):
    #    - Верхня частина над стінкою боксу ESP32 (Z_frame = 28.3 .. 37.5 мм по всій довжині)
    add_cap_box(-89.2, -24.5, 28.3, -43.0, -21.1, 37.5)
    #    - Права глибока колона в каньйоні між сервою та боксом ESP32 (X = -71.5 .. -43.0, Z_frame = 3.2 .. 28.3 мм)
    add_cap_box(-71.5, -24.5, 3.2, -43.0, -21.1, 28.3)
    #    - Ліва глибока колона зліва від боксу ESP32 (X = -89.2 .. -75.6, Z_frame = 3.2 .. 28.3 мм)
    add_cap_box(-89.2, -24.5, 3.2, -75.6, -21.1, 28.3)
