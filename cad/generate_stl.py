#!/usr/bin/env python3
"""
Повний генератор 3D-моделей Smart Light Switch (v4 — Фото 2 на стіні + Виступ вимикача 18 мм):
1. switch_mount_frame.stl:
   - Вікно №1 на весь вимикач: 83.0 x 82.4 мм.
   - Подіум під серву №2 (ЗЛІВА, точно як на Фото 2):
     * Оскільки найдальша точка клавіші вимикача виступає від стіни на 18.0 мм,
       дно ложа серви піднято на подіум висотою Z = 14.0 мм від стіни!
     * Тоді серва (товщиною 21.0 мм) лежить на Z = 14.0 .. 35.0 мм, а її вал (Точка 1)
       знаходиться на висоті Z_shaft = 14.0 + 10.5 = 24.5 мм від стіни (на 6.5 мм ВИЩЕ за 18-мм клавішу!).
     * По вертикалі (Y) ложе серви зміщено так (Y = -10.9 .. +31.9 мм), щоб вал серви (який на 10.5 мм від низу)
       стояв РІВНО ПО ЦЕНТРУ клавіші вимикача (Y = 0.0 мм)!
     * Додані спеціальні розширені ніші (56.6 мм по Y) під монтажні вушка серви (55 мм), щоб вушка не впиралися в стінки і фіксували серву від зсуву вправо-вліво, + нижній канал під вихід дроту серви.
   - Бокс №3 під ESP32 + конденсатор + дроти знизу + Трикутні косинки №4.
2. t_rocker_arm_25t.stl:
   - Паз знизу (Z = 0..5.4 мм) розміром 26.0 x 11.0 мм під кутом 45°, міжосьова відстань отворів 14.9 мм.
   - Дві вежі висотою Z = 0..28.0 мм (верхня ON на Y = +16.5..+25.0 мм, нижня OFF на Y = -25.0..-16.5 мм).
   - Натискні носики на висоті Z = 16.0..28.0 мм направлені В БІК СТІНИ (-X = -5.8 мм, як на Фото 2!):
     * У нейтралі (50°) носики висять на висоті 24.5 - 5.8 = 18.7 мм від стіни (рівно над 18.0-мм клавішею, не зачіпаючи її!).
     * При повороті серви на 25°..35° активний носик опускається до 11.5..8.0 мм від стіни, повністю втискаючи клавішу!
3. esp32_box_lid.stl — Кришка на защіпках на бокс ESP32.
"""

import struct
import math
import os


def write_binary_stl(filename, triangles):
    with open(filename, "wb") as f:
        header = b"SmartSwitch-25T-ExactFit-v4".ljust(80, b" ")
        f.write(header)
        f.write(struct.pack("<I", len(triangles)))
        for p1, p2, p3 in triangles:
            ux, uy, uz = p2[0] - p1[0], p2[1] - p1[1], p2[2] - p1[2]
            vx, vy, vz = p3[0] - p1[0], p3[1] - p1[1], p3[2] - p1[2]
            nx = uy * vz - uz * vy
            ny = uz * vx - ux * vz
            nz = ux * vy - uy * vx
            length = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
            nx, ny, nz = nx / length, ny / length, nz / length
            f.write(struct.pack("<12fH", nx, ny, nz, *p1, *p2, *p3, 0))


def add_hex(tris, v):
    faces = [
        (0, 2, 1), (0, 3, 2),
        (4, 5, 6), (4, 6, 7),
        (0, 1, 5), (0, 5, 4),
        (2, 3, 7), (2, 7, 6),
        (0, 4, 7), (0, 7, 3),
        (1, 2, 6), (1, 6, 5),
    ]
    for i, j, k in faces:
        tris.append((v[i], v[j], v[k]))


def add_box(tris, x0, y0, z0, x1, y1, z1):
    v = [
        (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
        (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)
    ]
    add_hex(tris, v)


def add_rot_box(tris, u0, v0, z0, u1, v1, z1, angle_deg):
    rad = math.radians(angle_deg)
    c, s = math.cos(rad), math.sin(rad)

    def rot(u, v, z):
        return (u * c - v * s, u * s + v * c, z)

    verts = [
        rot(u0, v0, z0), rot(u1, v0, z0), rot(u1, v1, z0), rot(u0, v1, z0),
        rot(u0, v0, z1), rot(u1, v0, z1), rot(u1, v1, z1), rot(u0, v1, z1),
    ]
    add_hex(tris, verts)


def add_wedge_y(tris, x0, x1, y_SupportBottom, y_BoxBottom, z_Wall, z_Out):
    L0 = (x0, y_SupportBottom, z_Wall)
    L1 = (x0, y_BoxBottom, z_Wall)
    L2 = (x0, y_BoxBottom, z_Out)

    R0 = (x1, y_SupportBottom, z_Wall)
    R1 = (x1, y_BoxBottom, z_Wall)
    R2 = (x1, y_BoxBottom, z_Out)

    tris.append((L0, L2, L1))
    tris.append((R0, R1, R2))
    tris.append((L0, L1, R1))
    tris.append((L0, R1, R0))
    tris.append((L1, L2, R2))
    tris.append((L1, R2, R1))
    tris.append((L0, R0, R2))
    tris.append((L0, R2, L2))


def generate_t_rocker_arm(out_path):
    """
    Насадка v4 під орієнтацію серви з Фото 2 та висоту вимикача 18.0 мм:
    - Коли дивимось на сріблястий торець серви (як на Фото 2):
      * +Y (12:00) — ВГОРУ (верхня половина клавіші вимикача ON)
      * -Y (6:00)  — ВНИЗ (нижня половина клавіші вимикача OFF)
      * -X (9:00)  — ДО СТІНИ (туди, де знаходиться клавіша вимикача на висоті 18.0 мм від стіни!)
      * +Z         — ВПРАВО вздовж сріблястого штифта (виліт 28 мм над клавішею вимикача)
    - Вал серви знаходиться на висоті Z_shaft = 24.5 мм від стіни.
    - Натискні носики на кінцях веж (Z = 16.0..28.0 мм) виступають у бік стіни до X = -5.8 мм:
      * У нейтралі (50°) носики знаходяться на 24.5 - 5.8 = 18.7 мм від стіни (на 0.7 мм вище за найдальшу точку клавіші 18.0 мм!).
      * При повороті серви на ±25..35° активний носик опускається до 11.5..7.7 мм від стіни, чітко перемикаючи клавішу!
    """
    tris = []
    ang = 18.0
    z_pocket = 5.4
    z_roof = 8.6

    # 1. Стінки паза під червоний ричажок (Z = 0.0 .. 8.6 мм), внутрішній паз: u=[-5.8..20.2] (26.0 мм), v=[-5.5..5.5] (11.0 мм)
    add_rot_box(tris, -18.5, -18.5, 0.0, 23.0, -5.5, z_roof, ang)
    add_rot_box(tris, -14.0,   5.5, 0.0, 23.0, 18.5, z_roof, ang)
    add_rot_box(tris, -18.5, -5.5, 0.0, -5.8, 14.0, z_roof, ang)
    add_rot_box(tris,  20.2, -5.5, 0.0, 23.0,  5.5, z_roof, ang)

    # 2. Дах над пазом (Z = 5.4 .. 8.6 мм) з двома точними отворами 3.8x3.8 мм на (0,0) та (+14.9, 0):
    add_rot_box(tris, -5.8, -5.5, z_pocket, 20.2, -1.9, z_roof, ang)
    add_rot_box(tris, -5.8,  1.9, z_pocket, 20.2,  5.5, z_roof, ang)
    add_rot_box(tris, -5.8, -1.9, z_pocket, -1.9,  1.9, z_roof, ang)
    add_rot_box(tris,  1.9, -1.9, z_pocket, 13.0,  1.9, z_roof, ang)
    add_rot_box(tris, 16.8, -1.9, z_pocket, 20.2,  1.9, z_roof, ang)

    # 3. ВЕРХНЯ НАТИСКНА ВЕЖА «ON» (12:00, Y = +16.5 .. +25.0 мм, Z = 0.0 .. 28.0 мм)
    # Стовп вежі над рамкою вимикача (Z = 0.0 .. 12.0 мм, X = -2.0 .. +5.5 мм — високо над рамкою!)
    add_box(tris, -2.0, 16.5, 0.0, 5.5, 25.0, 12.0)
    # 45° скіс під натискним носиком у бік стіни -X (Z = 12.0 .. 16.0 мм, X розширюється з -2.0 до -5.8 мм без сапортів!)
    add_hex(tris, [
        (-2.0, 16.5, 12.0), (5.5, 16.5, 12.0), (5.5, 25.0, 12.0), (-2.0, 25.0, 12.0),
        (-5.8, 16.5, 16.0), (5.5, 16.5, 16.0), (5.5, 25.0, 16.0), (-5.8, 25.0, 16.0),
    ])
    # Натискний носик над клавішею вимикача (Z = 16.0 .. 28.0 мм, X = -5.8 .. +5.5 мм — дивиться в бік стіни -X!)
    add_box(tris, -5.8, 16.5, 16.0, 5.5, 25.0, 28.0)

    # 4. НИЖНЯ НАТИСКНА ВЕЖА «OFF» (6:00, Y = -25.0 .. -16.5 мм, Z = 0.0 .. 28.0 мм)
    add_box(tris, -2.0, -25.0, 0.0, 5.5, -16.5, 12.0)
    add_hex(tris, [
        (-2.0, -25.0, 12.0), (5.5, -25.0, 12.0), (5.5, -16.5, 12.0), (-2.0, -16.5, 12.0),
        (-5.8, -25.0, 16.0), (5.5, -25.0, 16.0), (5.5, -16.5, 16.0), (-5.8, -16.5, 16.0),
    ])
    add_box(tris, -5.8, -25.0, 16.0, 5.5, -16.5, 28.0)

    write_binary_stl(out_path, tris)


def generate_switch_mount_frame(out_path):
    tris = []
    t_plate = 2.8
    wall = 3.2

    # 1. ВІКНО №1 НА ВЕСЬ ВИМИКАЧ (83.0 x 82.4 мм)
    wx0, wx1 = -41.5, 41.5
    wy0, wy1 = -41.2, 41.2

    # Права тонка планка (10 мм), верхня планка, ліва основа та нижня основа під скотч
    add_box(tris, wx1, wy0 - 12.0, 0.0, wx1 + 10.0, wy1 + 12.0, t_plate)
    add_box(tris, wx0 - 44.2, wy1, 0.0, wx1, wy1 + 12.0, t_plate)
    add_box(tris, wx0 - 44.2, wy0, 0.0, wx0, wy1, t_plate)
    add_box(tris, wx0 - 44.2, -106.0, 0.0, wx1, wy0, t_plate)

    # 2. ПОДІУМ + ЛОЖЕ СЕРВИ №2 (під Фото 2 та висоту вимикача 18.0 мм!):
    #    - Подіум Z = 0.0 .. 14.0 мм піднімає серву так, що вал серви знаходиться на Z = 24.5 мм від стіни (вище за 18-мм клавішу!)
    #    - По осі Y корпус серви (42 мм) лежить на Y = -10.9 .. +31.9 мм, тому вал серви (10.5 мм від низу) стоїть РІВНО на Y = 0.0 мм!
    #    - Спереду (X = -58.5 .. -45.5 мм) ніша розширена по Y до [-17.8 .. +38.8] під монтажні вушка серви (55 мм)!
    sx0, sx1 = -82.5, -43.0
    sy0, sy1 = -10.9, 31.9
    sy_ear0, sy_ear1 = -17.8, 38.8
    z_ped = 14.0
    z_servo = 35.2  # 14.0 + 21.2 мм

    # Масивний подіум під серву (Z = t_plate .. z_ped)
    add_box(tris, sx0 - wall, sy_ear0 - wall, t_plate, sx1, sy_ear1 + wall, z_ped)

    # Задня стінка ложа серви (X = sx0 - wall .. sx0)
    add_box(tris, sx0 - wall, sy0 - wall, z_ped, sx0, sy1 + wall, z_servo)

    # Задня частина бокових стінок (X = sx0 - wall .. -58.5 мм, тримає основне тіло 42 мм)
    add_box(tris, sx0 - wall, sy1, z_ped, -58.5, sy_ear1 + wall, z_servo)
    # Внизу залишаємо канал 15 мм (X = -82.5 .. -67.5) для вільного виходу дроту серви вниз (як на Фото 2!)
    add_box(tris, -67.5, sy_ear0 - wall, z_ped, -58.5, sy0, z_servo)

    # Передня частина бокових стінок навколо вушок 55 мм (X = -58.5 .. sx1)
    add_box(tris, -58.5, sy_ear1, z_ped, sx1, sy_ear1 + wall, z_servo)
    add_box(tris, -58.5, sy_ear0 - wall, z_ped, sx1, sy_ear0, z_servo)

    # Передні упори вушок серви (X = -45.5 .. sx1 — не дають серві зсунутися вправо до вимикача!)
    add_box(tris, -45.5, sy1, z_ped, sx1, sy_ear1, z_servo)
    add_box(tris, -45.5, sy_ear0, z_ped, sx1, sy0, z_servo)

    # Пружні ребра натягу (Crush Ribs 0.7 мм) вздовж тіла серви (затискають серву в лещата!)
    for rx in (-78.0, -66.0):
        add_box(tris, rx, sy1 - 0.7, z_ped + 2.0, rx + 2.4, sy1, z_servo - 2.0)
    add_box(tris, -65.0, sy0, z_ped + 2.0, -62.0, sy0 + 0.7, z_servo - 2.0)
    add_box(tris, sx0, -2.0, z_ped + 2.0, sx0 + 0.7,  4.0, z_servo - 2.0)
    add_box(tris, sx0, 16.0, z_ped + 2.0, sx0 + 0.7, 22.0, z_servo - 2.0)

    # Верхні защіпки-бортики (Snap-Fit lips на Z = z_servo .. z_servo + 2.2 мм — тримають серву зверху!)
    add_box(tris, sx0 - wall, sy1 - 1.2, z_servo, -58.5, sy1 + wall, z_servo + 2.2)
    add_box(tris, -67.5, sy0 - wall, z_servo, -58.5, sy0 + 1.2, z_servo + 2.2)

    # 3. БОКС №3 ПІД ESP32 + ДРОТИ + КОНДЕНСАТОР (ЗНИЗУ)
    bx0, bx1 = -72.0, 25.0
    by0, by1 = -104.0, wy0 - wall
    z_box = 28.0

    add_box(tris, bx0 - wall, by0, t_plate, bx0, sy_ear0 - wall, z_box)
    add_box(tris, bx1, by0, t_plate, bx1 + wall, by1 + wall, z_box)
    add_box(tris, sx1, by1, t_plate, bx1, by1 + wall, z_box)
    add_box(tris, bx0 - wall, by0 - wall, t_plate, -32.0, by0, z_box)
    add_box(tris, -14.0, by0 - wall, t_plate, bx1 + wall, by0, z_box)

    # Внутрішні тримачі під плату ESP32
    add_box(tris, -38.0, by0 + 4.0, t_plate, -35.5, by0 + 56.0, t_plate + 14.0)
    add_box(tris,  -6.5, by0 + 4.0, t_plate,  -4.0, by0 + 56.0, t_plate + 14.0)

    # 4. ТРИКУТНІ КОСИНКИ №4
    add_wedge_y(tris, bx0 - wall, bx0 + 2.0, -122.0, by0 - wall, t_plate, z_box)
    add_wedge_y(tris, bx1 - 2.0, bx1 + wall, -122.0, by0 - wall, t_plate, z_box)
    add_box(tris, bx0 - wall, -122.0, 0.0, bx1 + wall, by0 - wall, t_plate)

    write_binary_stl(out_path, tris)


